/* gen_tables <tables-dir> <out.h>
 * Reads TOK.bin, LL.bin, ML.bin, LIT.bin, OWN.bin, checks each against the SHA-256 that
 * format.md ("The tables") gives, and writes them as C arrays. C11, standard library only. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

