#define ROR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

static void sha256_block(uint32_t h[8], const unsigned char *p)
{
    uint32_t w[64], a, b, c, d, e, f, g, hh;
    for (int i = 0; i < 16; i++)
        w[i] = (uint32_t)p[4 * i] << 24 | (uint32_t)p[4 * i + 1] << 16 | (uint32_t)p[4 * i + 2] << 8 | p[4 * i + 3];
    for (int i = 16; i < 64; i++) {
        uint32_t s0 = ROR(w[i - 15], 7) ^ ROR(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = ROR(w[i - 2], 17) ^ ROR(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    a = h[0]; b = h[1]; c = h[2]; d = h[3]; e = h[4]; f = h[5]; g = h[6]; hh = h[7];
    for (int i = 0; i < 64; i++) {
        uint32_t t1 = hh + (ROR(e, 6) ^ ROR(e, 11) ^ ROR(e, 25)) + ((e & f) ^ (~e & g)) + K[i] + w[i];
        uint32_t t2 = (ROR(a, 2) ^ ROR(a, 13) ^ ROR(a, 22)) + ((a & b) ^ (a & c) ^ (b & c));
        hh = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
    }
    h[0] += a; h[1] += b; h[2] += c; h[3] += d; h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
}

static void sha256_hex(const unsigned char *m, size_t n, char out[65])
{
    uint32_t h[8] = {0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19};
    unsigned char buf[128];
    size_t i = 0;
    for (; i + 64 <= n; i += 64) sha256_block(h, m + i);
    size_t r = n - i;
    memset(buf, 0, sizeof buf);
    memcpy(buf, m + i, r);
    buf[r] = 0x80;
    size_t tot = (r + 9 <= 64) ? 64 : 128;
    uint64_t bits = (uint64_t)n * 8;
    for (int k = 0; k < 8; k++) buf[tot - 1 - k] = (unsigned char)(bits >> (8 * k));
    sha256_block(h, buf);
    if (tot == 128) sha256_block(h, buf + 64);
    for (int k = 0; k < 8; k++) sprintf(out + 8 * k, "%08x", (unsigned)h[k]);
}

struct tab { const char *name, *cname, *sha; size_t len; };
static const struct tab tabs[] = {
    {"TOK", "cr_len_tok", "c5f97d70cd50ed0e3517c69231437fd534f5e772bb9ed70dc3769a3337b2d6e0", 3073},
    {"LL", "cr_len_ll", "ce0b70bdefdad678f22ef1139cf8284c48b61f720adb007b0a28b0ad3777bf16", 24},
    {"ML", "cr_len_ml", "c39358b16a14c2462e092ee13b345e9b5002e59c5efc9521f0967063a7873289", 24},
    {"LIT", "cr_len_lit", "43f552dca80dcdffd6dc21231555f1c938580650a1b90b94b8c515120ad9ad9e", 2048},
    {"OWN", "cr_len_own", "96312d8701c3fa72a06db3dcdb982aab0075aaac91bc895cf1eed3ae88e00721", 19},
};

int main(int argc, char **argv)
{
    if (argc != 3) { fprintf(stderr, "usage: gen_tables <tables-dir> <out.h>\n"); return 2; }
    FILE *o = fopen(argv[2], "w");
    if (!o) { perror(argv[2]); return 1; }
    fprintf(o, "/* Generated by gen_tables from %s; SHA-256 checked against format.md. */\n", argv[1]);
    for (size_t t = 0; t < sizeof tabs / sizeof tabs[0]; t++) {
        char path[4096], hex[65];
        snprintf(path, sizeof path, "%s/%s.bin", argv[1], tabs[t].name);
        FILE *f = fopen(path, "rb");
        if (!f) { perror(path); return 1; }
        unsigned char buf[4096];
        size_t n = fread(buf, 1, sizeof buf, f);
        fclose(f);
        if (n != tabs[t].len) { fprintf(stderr, "%s: %zu bytes, expected %zu\n", path, n, tabs[t].len); return 1; }
        sha256_hex(buf, n, hex);
        if (strcmp(hex, tabs[t].sha) != 0) { fprintf(stderr, "%s: SHA-256 %s, expected %s\n", path, hex, tabs[t].sha); return 1; }
        fprintf(o, "static const unsigned char %s[%zu] = {", tabs[t].cname, n);
        for (size_t i = 0; i < n; i++) fprintf(o, "%s%u%s", i % 32 ? "" : "\n    ", buf[i], i + 1 < n ? "," : "");
        fprintf(o, "\n};\n");
        fprintf(stderr, "%s: SHA-256 ok\n", tabs[t].name);
    }
    fclose(o);
    return 0;
}
