#!/usr/bin/env python3
"""Make cr_tables.h from tables/*.bin, after checking each against the SHA-256 in format.md."""
import hashlib, sys, os

SHA = {
    "TOK": "c5f97d70cd50ed0e3517c69231437fd534f5e772bb9ed70dc3769a3337b2d6e0",
    "LL":  "ce0b70bdefdad678f22ef1139cf8284c48b61f720adb007b0a28b0ad3777bf16",
    "ML":  "c39358b16a14c2462e092ee13b345e9b5002e59c5efc9521f0967063a7873289",
    "LIT": "43f552dca80dcdffd6dc21231555f1c938580650a1b90b94b8c515120ad9ad9e",
    "OWN": "96312d8701c3fa72a06db3dcdb982aab0075aaac91bc895cf1eed3ae88e00721",
}
SIZE = {"TOK": 3073, "LL": 24, "ML": 24, "LIT": 8 * 256, "OWN": 19}
MAXLEN = {"TOK": 11, "LL": 8, "ML": 8, "LIT": 10, "OWN": 8}

def complete(lengths):
    return sum(1 << (32 - l) for l in lengths if l) == 1 << 32

def main(tdir, outpath):
    out = ["/* Generated by tools/gen_tables.py from the files in tables/. Do not edit. */",
           "#ifndef CR_TABLES_H", "#define CR_TABLES_H", ""]
    for name in ["TOK", "LL", "ML", "LIT", "OWN"]:
        data = open(os.path.join(tdir, name + ".bin"), "rb").read()
        h = hashlib.sha256(data).hexdigest()
        if h != SHA[name]:
            sys.exit(f"{name}: SHA-256 {h} != {SHA[name]}")
        if len(data) != SIZE[name]:
            sys.exit(f"{name}: {len(data)} bytes, expected {SIZE[name]}")
        parts = [data[i:i + 256] for i in range(0, 2048, 256)] if name == "LIT" else [data]
        for p in parts:
            if max(p) > MAXLEN[name] or not complete(p):
                sys.exit(f"{name}: not a complete code of at most {MAXLEN[name]} bits")
        out.append(f"static const unsigned char cr_len_{name.lower()}[{len(data)}] = {{")
        for i in range(0, len(data), 32):
            out.append("  " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    open(outpath, "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
