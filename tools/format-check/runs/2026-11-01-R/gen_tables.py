#!/usr/bin/env python3
# Generates seqlz_tables.h from the binary code-length tables in tables/.
# Each table's bytes are verified against the SHA-256 that seqlz.rst gives
# before they are embedded, exactly as the spec's table requires.
import hashlib, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
TBL = os.path.join(HERE, "tables")

# SHA-256 values quoted from seqlz.rst, section "The tables".
SHA = {
    "TOK": "c5f97d70cd50ed0e3517c69231437fd534f5e772bb9ed70dc3769a3337b2d6e0",
    "LL":  "ce0b70bdefdad678f22ef1139cf8284c48b61f720adb007b0a28b0ad3777bf16",
    "ML":  "c39358b16a14c2462e092ee13b345e9b5002e59c5efc9521f0967063a7873289",
    "LIT": "43f552dca80dcdffd6dc21231555f1c938580650a1b90b94b8c515120ad9ad9e",
    "OWN": "96312d8701c3fa72a06db3dcdb982aab0075aaac91bc895cf1eed3ae88e00721",
}
SIZE = {"TOK": 3073, "LL": 24, "ML": 24, "LIT": 2048, "OWN": 19}

def load(name):
    with open(os.path.join(TBL, name + ".bin"), "rb") as f:
        data = f.read()
    h = hashlib.sha256(data).hexdigest()
    if h != SHA[name]:
        sys.exit("SHA-256 mismatch for %s: got %s, want %s" % (name, h, SHA[name]))
    if len(data) != SIZE[name]:
        sys.exit("size mismatch for %s: got %d, want %d" % (name, len(data), SIZE[name]))
    return data

tok = load("TOK"); ll = load("LL"); ml = load("ML"); lit = load("LIT"); own = load("OWN")

def arr(name, data, perline=20):
    out = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), perline):
        out.append("  " + ",".join(str(b) for b in data[i:i+perline]) + ",")
    out.append("};")
    return "\n".join(out)

with open(os.path.join(HERE, "seqlz_tables.h"), "w") as f:
    f.write("/* Generated by gen_tables.py from the table binaries. Do not edit. */\n")
    f.write("#ifndef SEQLZ_TABLES_H\n#define SEQLZ_TABLES_H\n\n")
    f.write(arr("seqlz_tok_len", tok) + "\n\n")
    f.write(arr("seqlz_ll_len", ll) + "\n\n")
    f.write(arr("seqlz_ml_len", ml) + "\n\n")
    f.write(arr("seqlz_own_len", own) + "\n\n")
    # 8 literal tables of 256 lengths each, one after the other.
    f.write("static const unsigned char seqlz_lit_len[8][256] = {\n")
    for t in range(8):
        chunk = lit[t*256:(t+1)*256]
        f.write("  {\n")
        for i in range(0, 256, 20):
            f.write("   " + ",".join(str(b) for b in chunk[i:i+20]) + ",\n")
        f.write("  },\n")
    f.write("};\n\n")
    f.write("#endif\n")

print("seqlz_tables.h written, all SHA-256 verified")
