#!/usr/bin/env python3
"""Make src/cr_tables.h from tables/*.bin, after checking each against the SHA-256 in format.md."""
import hashlib, sys, os

SHA = {  # from format.md, section "The tables"
    "TOK": ("c5f97d70cd50ed0e3517c69231437fd534f5e772bb9ed70dc3769a3337b2d6e0", 3073),
    "LL":  ("ce0b70bdefdad678f22ef1139cf8284c48b61f720adb007b0a28b0ad3777bf16", 24),
    "ML":  ("c39358b16a14c2462e092ee13b345e9b5002e59c5efc9521f0967063a7873289", 24),
    "LIT": ("43f552dca80dcdffd6dc21231555f1c938580650a1b90b94b8c515120ad9ad9e", 8 * 256),
    "OWN": ("96312d8701c3fa72a06db3dcdb982aab0075aaac91bc895cf1eed3ae88e00721", 19),
}
MAXLEN = {"TOK": 11, "LL": 8, "ML": 7, "LIT": 10, "OWN": 8}

def main(tables_dir, out_path):
    lines = ["/* Generated by tools/gen_tables.py from the files in tables/. Do not edit. */",
             "#ifndef CR_TABLES_H", "#define CR_TABLES_H", ""]
    for name, (sha, size) in SHA.items():
        data = open(os.path.join(tables_dir, name + ".bin"), "rb").read()
        if hashlib.sha256(data).hexdigest() != sha or len(data) != size:
            sys.exit(f"{name}.bin: SHA-256 or size does not match format.md")
        parts = [data] if name != "LIT" else [data[i * 256:(i + 1) * 256] for i in range(8)]
        for p in parts:
            if max(p) > MAXLEN[name]:
                sys.exit(f"{name}: code longer than {MAXLEN[name]} bits")
            # complete: sum of 2^-l is exactly 1
            if sum(1 << (MAXLEN[name] - l) for l in p if l) != 1 << MAXLEN[name]:
                sys.exit(f"{name}: not complete")
        lines.append(f"/* {name}: SHA-256 {sha} */")
        lines.append(f"static const unsigned char cr_len_{name}[{size}] = {{")
        for i in range(0, size, 32):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
