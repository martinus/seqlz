/* mktables <tabledir> <out.h>: reads TOK.bin, LL.bin, ML.bin, LIT.bin, OWN.bin, checks each
 * against the SHA-256 that format.md gives (section "The tables"), checks that each table is a
 * complete prefix code, and writes them as C arrays. C11, standard library only. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static const uint32_t K[64] = {
    0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,
    0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,
    0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,
    0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,
    0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,
    0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,
    0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,
    0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2};

#define ROR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

static void sha256_hex(const unsigned char *d, size_t len, char hex[65]) {
    uint32_t h[8] = {0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19};
    size_t total = ((len + 9 + 63) / 64) * 64;
    unsigned char *m = calloc(total, 1);
    if (!m) { perror("calloc"); exit(1); }
    memcpy(m, d, len);
    m[len] = 0x80;
    uint64_t bits = (uint64_t)len * 8;
    for (int i = 0; i < 8; i++) m[total - 1 - i] = (unsigned char)(bits >> (8 * i));
    for (size_t off = 0; off < total; off += 64) {
        uint32_t w[64];
        for (int i = 0; i < 16; i++)
            w[i] = (uint32_t)m[off + 4*i] << 24 | (uint32_t)m[off + 4*i + 1] << 16 |
                   (uint32_t)m[off + 4*i + 2] << 8 | m[off + 4*i + 3];
        for (int i = 16; i < 64; i++) {
            uint32_t s0 = ROR(w[i-15], 7) ^ ROR(w[i-15], 18) ^ (w[i-15] >> 3);
            uint32_t s1 = ROR(w[i-2], 17) ^ ROR(w[i-2], 19) ^ (w[i-2] >> 10);
            w[i] = w[i-16] + s0 + w[i-7] + s1;
        }
        uint32_t a=h[0],b=h[1],c=h[2],dd=h[3],e=h[4],f=h[5],g=h[6],hh=h[7];
        for (int i = 0; i < 64; i++) {
            uint32_t t1 = hh + (ROR(e,6) ^ ROR(e,11) ^ ROR(e,25)) + ((e & f) ^ (~e & g)) + K[i] + w[i];
            uint32_t t2 = (ROR(a,2) ^ ROR(a,13) ^ ROR(a,22)) + ((a & b) ^ (a & c) ^ (b & c));
            hh = g; g = f; f = e; e = dd + t1; dd = c; c = b; b = a; a = t1 + t2;
        }
        h[0]+=a; h[1]+=b; h[2]+=c; h[3]+=dd; h[4]+=e; h[5]+=f; h[6]+=g; h[7]+=hh;
    }
    free(m);
    for (int i = 0; i < 8; i++) sprintf(hex + 8 * i, "%08x", (unsigned)h[i]);
}

struct tab { const char *name, *file, *sha; size_t len; int parts; };
static const struct tab tabs[] = {
    {"TOK", "TOK.bin", "c5f97d70cd50ed0e3517c69231437fd534f5e772bb9ed70dc3769a3337b2d6e0", 3073, 1},
    {"LL",  "LL.bin",  "ce0b70bdefdad678f22ef1139cf8284c48b61f720adb007b0a28b0ad3777bf16", 24, 1},
    {"ML",  "ML.bin",  "c39358b16a14c2462e092ee13b345e9b5002e59c5efc9521f0967063a7873289", 24, 1},
    {"LIT", "LIT.bin", "43f552dca80dcdffd6dc21231555f1c938580650a1b90b94b8c515120ad9ad9e", 2048, 8},
    {"OWN", "OWN.bin", "96312d8701c3fa72a06db3dcdb982aab0075aaac91bc895cf1eed3ae88e00721", 19, 1},
};

int main(int argc, char **argv) {
    if (argc != 3) { fprintf(stderr, "usage: mktables <tabledir> <out.h>\n"); return 2; }
    FILE *out = fopen(argv[2], "w");
    if (!out) { perror(argv[2]); return 1; }
    fprintf(out, "/* generated by mktables from %s, SHA-256 checked */\n", argv[1]);
    for (size_t t = 0; t < sizeof tabs / sizeof tabs[0]; t++) {
        char path[4096];
        snprintf(path, sizeof path, "%s/%s", argv[1], tabs[t].file);
        FILE *f = fopen(path, "rb");
        if (!f) { perror(path); return 1; }
        unsigned char buf[4096];
        size_t len = fread(buf, 1, sizeof buf, f);
        fclose(f);
        if (len != tabs[t].len) { fprintf(stderr, "%s: %zu bytes, want %zu\n", path, len, tabs[t].len); return 1; }
        char hex[65];
        sha256_hex(buf, len, hex);
        if (strcmp(hex, tabs[t].sha) != 0) { fprintf(stderr, "%s: SHA-256 %s, want %s\n", path, hex, tabs[t].sha); return 1; }
        size_t per = len / tabs[t].parts;
        for (int p = 0; p < tabs[t].parts; p++) {   /* complete: sum 2^-l == 1, l <= 15 */
            uint64_t sum = 0;
            for (size_t i = 0; i < per; i++) {
                unsigned l = buf[p * per + i];
                if (l > 15) { fprintf(stderr, "%s: length %u\n", path, l); return 1; }
                if (l) sum += (uint64_t)1 << (15 - l);
            }
            if (sum != (uint64_t)1 << 15) { fprintf(stderr, "%s part %d: not complete\n", path, p); return 1; }
        }
        fprintf(out, "static const unsigned char %s_LEN[%zu] = {", tabs[t].name, len);
        for (size_t i = 0; i < len; i++) fprintf(out, "%s%u,", i % 32 ? "" : "\n", buf[i]);
        fprintf(out, "\n};\n");
        printf("%s: %s ok\n", tabs[t].name, hex);
    }
    return fclose(out) != 0;
}
