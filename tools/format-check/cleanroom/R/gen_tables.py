#!/usr/bin/env python3
"""Generate seqlz_tables.h from the code-length tables in tables/.

Each table file holds one byte per symbol: the code length, 0 for a symbol
with no code. LIT.bin is the 8 literal tables one after the other (256 each).
Each file is checked against the SHA-256 that seqlz.rst gives before it is
emitted. Run from the directory that holds tables/.
"""
import hashlib
import sys

# SHA-256 values quoted from seqlz.rst, section "The tables".
SHA = {
    "TOK": "c5f97d70cd50ed0e3517c69231437fd534f5e772bb9ed70dc3769a3337b2d6e0",
    "LL":  "ce0b70bdefdad678f22ef1139cf8284c48b61f720adb007b0a28b0ad3777bf16",
    "ML":  "c39358b16a14c2462e092ee13b345e9b5002e59c5efc9521f0967063a7873289",
    "LIT": "43f552dca80dcdffd6dc21231555f1c938580650a1b90b94b8c515120ad9ad9e",
    "OWN": "96312d8701c3fa72a06db3dcdb982aab0075aaac91bc895cf1eed3ae88e00721",
}

SIZES = {"TOK": 3073, "LL": 24, "ML": 24, "LIT": 2048, "OWN": 19}


def load(name):
    data = open("tables/%s.bin" % name, "rb").read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA[name]:
        sys.exit("SHA-256 mismatch for %s: got %s, want %s" % (name, got, SHA[name]))
    if len(data) != SIZES[name]:
        sys.exit("size mismatch for %s: got %d, want %d" % (name, len(data), SIZES[name]))
    return data


def emit_array(out, decl, data):
    out.append("static const unsigned char %s = {" % decl)
    line = "   "
    for i, b in enumerate(data):
        piece = " %d," % b
        if len(line) + len(piece) > 96:
            out.append(line)
            line = "   "
        line += piece
    if line.strip():
        out.append(line)
    out.append("};")
    out.append("")


def main():
    tok = load("TOK")
    ll = load("LL")
    ml = load("ML")
    lit = load("LIT")
    own = load("OWN")

    out = []
    out.append("/* Generated by gen_tables.py from the table binaries. Do not edit. */")
    out.append("/* Each array is one code length per symbol, 0 = no code. */")
    out.append("#ifndef SEQLZ_TABLES_H")
    out.append("#define SEQLZ_TABLES_H")
    out.append("")
    emit_array(out, "seqlz_tok_len[3073]", tok)
    emit_array(out, "seqlz_ll_len[24]", ll)
    emit_array(out, "seqlz_ml_len[24]", ml)
    # LIT as 8x256
    out.append("static const unsigned char seqlz_lit_len[8][256] = {")
    for t in range(8):
        block = lit[t * 256:t * 256 + 256]
        out.append("  {")
        line = "   "
        for b in block:
            piece = " %d," % b
            if len(line) + len(piece) > 96:
                out.append(line)
                line = "   "
            line += piece
        if line.strip():
            out.append(line)
        out.append("  },")
    out.append("};")
    out.append("")
    emit_array(out, "seqlz_own_len[19]", own)
    out.append("#endif /* SEQLZ_TABLES_H */")

    open("seqlz_tables.h", "w").write("\n".join(out) + "\n")
    print("wrote seqlz_tables.h")


if __name__ == "__main__":
    main()
